-- INNER JOIN: 연결할 데이터가 없으면 나오지 않음
SELECT * 
FROM INFO 
INNER JOIN AUTH -- INNER는 생략 가능함
ON INFO.AUTH_ID = AUTH.AUTH_ID;
-- 테이블 엘리어스
SELECT *
FROM INFO I
JOIN AUTH A
ON I.AUTH_ID = A.AUTH_ID;
-- SELECT 구문의 선택 - 동일한 컬럼명이 있는 경우에 참조테이블을 지정해야 한다.
SELECT ID,
       TITLE,
       I.AUTH_ID,
       NAME
FROM INFO I
JOIN AUTH A
ON I.AUTH_ID = A.AUTH_ID;
-- USING ON 구문을 쓸수도 있음
SELECT *
FROM INFO I
JOIN AUTH A
USING (AUTH_ID);


-- LEFT OUTER JOIN
SELECT * 
FROM INFO 
LEFT OUTER JOIN AUTH  -- OUTER 생략 가능
ON INFO.AUTH_ID = AUTH.AUTH_ID;
-- RIGHT OUTER JOIN
SELECT *
FROM INFO I
RIGHT OUTER JOIN AUTH A -- OUTER 생략 가능
ON I.AUTH_ID = A.AUTH_ID;
-- FULL JOIN
SELECT *
FROM INFO I
FULL JOIN AUTH A
ON I.AUTH_ID = A.AUTH_ID;

-- CROSS JOIN - 카타시안 프로덕트
SELECT *
FROM INFO CROSS JOIN AUTH;
