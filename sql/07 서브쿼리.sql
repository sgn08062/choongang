-- 스칼라 쿼리 (서브쿼리절이 select 구문에 들어간 형태)
-- LEFT JOIN을 대체할 수 있음 (조인된 테이블의 1개 컬럼을 가져올 때 유리함)
SELECT FIRST_NAME,
       D.DEPARTMENT_NAME
FROM EMPLOYEES E
LEFT JOIN DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID;

SELECT FIRST_NAME,
       (SELECT DEPARTMENT_NAME FROM DEPARTMENTS D WHERE D.DEPARTMENT_ID = E.DEPARTMENT_ID) AS DEPARTMENT_NAME
FROM EMPLOYEES E;
-- 각 직원의 부서명, 직무이름을 가지고 올 것임
SELECT FIRST_NAME, 
       (SELECT DEPARTMENT_NAME FROM DEPARTMENTS D WHERE D.DEPARTMENT_ID = E.DEPARTMENT_ID) AS D_NAME,
       (SELECT JOB_TITLE FROM JOBS J WHERE E.JOB_ID = J.JOB_ID) AS J_TITLE
FROM EMPLOYEES E;

-- 테이블 엘리어스
SELECT E.*, 
       (SELECT DEPARTMENT_NAME FROM DEPARTMENTS D WHERE D.DEPARTMENT_ID = E.DEPARTMENT_ID) AS D_NAME,
       (SELECT JOB_TITLE FROM JOBS J WHERE E.JOB_ID = J.JOB_ID) AS J_TITLE
FROM EMPLOYEES E;

SELECT
