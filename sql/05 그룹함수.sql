--그룹함수
--AVG, SUM, MAX, MIN, COUNT(*), COUNT(컬럼)
SELECT SUM(SALARY), AVG(SALARY), MAX(SALARY), MIN(SALARY), COUNT(SALARY)
FROM EMPLOYEES WHERE JOB_ID LIKE 'SA%';

--MIN, MAX는 날짜타입, 문자에도 적용됨
SELECT MIN(HIRE_DATE), MAX(HIRE_DATE) FROM EMPLOYEES;
SELECT MIN(FIRST_NAME), MAX(FIRST_NAME) FROM EMPLOYEES;
--COUNT() 사용방법 2가지
SELECT COUNT(*), -- 전체 행 수
       COUNT(COMMISSION_PCT) -- NULL이 아닌 데이터의 개수 
FROM EMPLOYEES;

-- 그룹함수를 쓸 때 자주하는 실수 - 일반컬럼, 그룹함수를 같이 사용함
SELECT FIRST_NAME, SUM(SALARY) FROM EMPLOYEES;
-- WINDOW절을 사용하면 일반컬럼 옆에 그룹함수 값을 동시에 붙여서 사용할 수 있음
SELECT FIRST_NAME, 
        SUM(SALARY) OVER(),
        MAX(SALARY) OVER(),
        MIN(SALARY) OVER(),
        AVG(SALARY) OVER()
FROM EMPLOYEES;

-- GROUP BY
SELECT DEPARTMENT_ID, AVG(SALARY)
FROM EMPLOYEES
GROUP BY DEPARTMENT_ID;
-- 그룹함수를 같이 사용 가능
SELECT DEPARTMENT_ID,
       SUM(SALARY),
       AVG(SALARY),
       COUNT(*),
       MAX(SALARY),
       MIN(SALARY)
FROM EMPLOYEES
GROUP BY DEPARTMENT_ID;
-- 주의할 점 - 그룹화하지 않은 칼럼을 SELECT절에 바로 넣을 수 없음

-- 2개 이상의 그룹화
SELECT DEPARTMENT_ID, JOB_ID
FROM EMPLOYEES
GROUP BY DEPARTMENT_ID, JOB_ID
ORDER BY DEPARTMENT_ID;

-- GROUP BY의 조건을 쓰는 절은 WHERE이 아닌 HAVING
-- 평균 급여가 6000이상인 부서만 출력
SELECT DEPARTMENT_ID, AVG(SALARY)
FROM EMPLOYEES
GROUP BY DEPARTMENT_ID
HAVING AVG(SALARY) >= 6000;

SELECT DEPARTMENT_ID, AVG(SALARY)
FROM EMPLOYEES
WHERE DEPARTMENT_ID IS NOT NULL
GROUP BY DEPARTMENT_ID
HAVING AVG(SALARY) > 6000;

-- 샐러리맨이 아닌 사람들의, 직무별 급여 평균이 6000 이상인 데이터, 평균, 합계, 평균 내림차순으로 정렬
SELECT JOB_ID, TRUNC(AVG(SALARY)) 평균, SUM(SALARY)합계
FROM EMPLOYEES
WHERE JOB_ID NOT LIKE 'SA%'
GROUP BY JOB_ID
HAVING AVG(SALARY) >= 6000
ORDER BY 평균 DESC;

