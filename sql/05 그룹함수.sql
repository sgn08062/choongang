-- ROLLUP
SELECT DEPARTMENT_ID, ROUND(AVG(SALARY), 2), COUNT(*)
FROM EMPLOYEES
GROUP BY ROLLUP(DEPARTMENT_ID)
ORDER BY DEPARTMENT_ID;

SELECT DEPARTMENT_ID, JOB_ID, ROUND(AVG(SALARY), 2), COUNT(*)
FROM EMPLOYEES
GROUP BY ROLLUP(DEPARTMENT_ID, JOB_ID)
ORDER BY DEPARTMENT_ID, JOB_ID;

-- CUBE = ROLLUP + 서브그룹의 총계까지 추가
SELECT DEPARTMENT_ID, JOB_ID, ROUND(AVG(SALARY), 2), COUNT(*)
FROM EMPLOYEES
GROUP BY CUBE(DEPARTMENT_ID, JOB_ID)
ORDER BY DEPARTMENT_ID;

-- GROUPING - GROUP BY로 생성되었으면 0 반환, ROLLUP OR CUBE로 생성되었으면 1 반환
SELECT DECODE(GROUPING(DEPARTMENT_ID),1, '총계', DEPARTMENT_ID),
       DECODE(GROUPING(JOB_ID), 1, '소계', JOB_ID), 
       SUM(SALARY),
       GROUPING(DEPARTMENT_ID),
       GROUPING(JOB_ID)
FROM EMPLOYEES
GROUP BY ROLLUP(DEPARTMENT_ID,JOB_ID)
ORDER BY DEPARTMENT_ID;



