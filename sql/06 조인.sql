--EMPLOYEES 테이블에서 left join하여 관리자(매니저)와, 매니저의 이름, 매니저의 급여 까지 출력하세요
--조건) 매니저 아이디가 없는 사람은 배제하고 급여는 역순으로 출력하세요
SELECT CONCAT(E1.FIRST_NAME, E1.LAST_NAME) 사원명, E1.MANAGER_ID 매니저_아이디, 
       CONCAT(E2.FIRST_NAME, E2.LAST_NAME) 매니저명, E2.SALARY 매니저_급여
FROM EMPLOYEES E1
LEFT JOIN EMPLOYEES E2 ON E1.MANAGER_ID = E2.EMPLOYEE_ID
WHERE E1.MANAGER_ID IS NOT NULL
ORDER BY E2.SALARY DESC;