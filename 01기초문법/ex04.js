/* 
    변수의 선언방법
    var 이름;
*/

var a;

a = 1;

console.log(a);

var b = 10;
console.log(b);

var b = "홍길동";
console.log(b);


// 변수의 값을 다른 변수에 저장
var result = a + 100;
console.log(result);

/* 
    const = 상수
    상수의 변수 이름은 대문자에 _를 사용한다.
    선언 즉시 초기화를 해야하며 선언된 값은 변경이 불가능하다.
*/
const EARTH_RADIUS = 6400;
console.log(EARTH_RADIUS);
