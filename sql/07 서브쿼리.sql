-- 인라인뷰 (FROM에 들어가는 서브쿼리)
-- 인라인뷰에서 만든 가상 칼럼들에 대해서 연속적으로 조회해 나갈 때 사용함

-- ROWNUM은 조회된 순서에 번호가 붙음. ORDER BY하면서 순서가 뒤바뀜
SELECT ROWNUM,
       FIRST_NAME,
       SALARY
FROM EMPLOYEES
ORDER BY SALARY DESC;

-- 해결하기 위해 인라인 뷰를 한다
SELECT ROWNUM, FIRST_NAME, SALARY
FROM (SELECT FIRST_NAME, SALARY
      FROM EMPLOYEES
      ORDER BY SALARY DESC)
WHERE ROWNUM BETWEEN 11 AND 20; -- ROWNUM은 순서 붙이기라서 1번부터만 가능. 11번부터 시작해서 안나옴

-- 한번 더 인라인 뷰를 중첩시켜 해결한다.
SELECT RNUM, FIRST_NAME, SALARY
FROM(SELECT ROWNUM RNUM, FIRST_NAME, SALARY
     FROM (SELECT FIRST_NAME, SALARY
           FROM EMPLOYEES
           ORDER BY SALARY DESC)
    )
WHERE RNUM BETWEEN 11 AND 20;

